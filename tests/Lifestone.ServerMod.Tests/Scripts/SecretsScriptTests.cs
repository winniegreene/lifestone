using Lifestone.ServerMod.Tests.Support;

namespace Lifestone.ServerMod.Tests.Scripts;

/// <summary>
/// secrets.json schema 2 (m2-plan SM5, owner decision D10) through server\lib\LifestoneServer.psm1, in Windows
/// PowerShell 5.1 and PowerShell 7: a new file, the schema-1 migration (no login lost), -AddAccount, the protected
/// write path and the leak scan. Every file is a temporary one with test values made here; nothing reads the real
/// server\runtime\secrets.json, and no run may print a password.
/// </summary>
public sealed class SecretsScriptTests
{
    /// <summary>The shells the scripts must work in.</summary>
    public static TheoryData<string> Shells => PowerShellHost.Shells;

    private static string Config(TempFolder folder) =>
        "$cfg = Get-LsConfig\n$cfg.Secrets = " + PowerShellHost.Quote(folder.Combine("secrets.json")) + "\n";

    [Theory]
    [MemberData(nameof(Shells))]
    public void A_new_secrets_file_is_schema_2_with_a_play_and_a_test_account(string shell)
    {
        using var folder = new TempFolder();
        var run = PowerShellHost.RunOk(shell, Config(folder) + "$r = Initialize-LsSecrets $cfg\nOut-Result $r.Action\n");
        Assert.Equal("created", run.Result?.GetString());

        using var secrets = ReadSecrets(folder);
        var root = secrets.RootElement;
        Assert.Equal(2, root.GetProperty("schema").GetInt32());
        Assert.Equal("play", root.GetProperty("defaultAccount").GetString());
        var accounts = root.GetProperty("accounts");
        Assert.Equal(["play", "test"], accounts.EnumerateObject().Select(p => p.Name));
        Assert.Equal("lifestone", accounts.GetProperty("play").GetProperty("username").GetString());
        Assert.Equal("lifestone-test", accounts.GetProperty("test").GetProperty("username").GetString());
        foreach (var key in new[] { "play", "test" })
        {
            Assert.Matches("^[A-Za-z0-9]{20}$", accounts.GetProperty(key).GetProperty("password").GetString());
        }

        var mariadb = root.GetProperty("mariadb");
        Assert.Equal("127.0.0.1", mariadb.GetProperty("host").GetString());
        Assert.Equal(3316, mariadb.GetProperty("port").GetInt32());
        Assert.Matches("^[A-Za-z0-9]{32}$", mariadb.GetProperty("rootPassword").GetString());
        Assert.Matches("^[A-Za-z0-9]{32}$", mariadb.GetProperty("acePassword").GetString());
        Assert.False(root.TryGetProperty("testAccount", out _));
        AssertOwnerOnly(folder.Combine("secrets.json"));
        AssertNoPasswordIn(run, secrets);
        Assert.False(File.Exists(folder.Combine("secrets.json.tmp")));
    }

    [Theory]
    [MemberData(nameof(Shells))]
    public void A_schema_1_file_is_migrated_without_losing_a_login(string shell)
    {
        using var folder = new TempFolder();
        var root = Random(32);
        var ace = Random(32);
        var play = Random(20);
        var v1 = $$"""
            {
              "note": "Generated by server/setup-server.ps1.",
              "generatedUtc": "2026-10-09T23:30:00.0000000Z",
              "mariadb": { "host": "127.0.0.1", "port": 3316, "rootUser": "root", "rootPassword": "{{root}}", "aceUser": "ace", "acePassword": "{{ace}}" },
              "testAccount": { "username": "lifestone", "password": "{{play}}", "note": "ACE auto-creates this account on first login." }
            }
            """;
        File.WriteAllText(folder.Combine("secrets.json"), v1, new UTF8Encoding(false));

        var run = PowerShellHost.RunOk(shell, Config(folder) + "$r = Initialize-LsSecrets $cfg\nOut-Result $r.Action\n");
        Assert.Equal("migrated", run.Result?.GetString());
        using (var secrets = ReadSecrets(folder))
        {
            var doc = secrets.RootElement;
            Assert.Equal(2, doc.GetProperty("schema").GetInt32());
            Assert.False(doc.TryGetProperty("testAccount", out _));
            Assert.Equal("2026-10-09T23:30:00.0000000Z", doc.GetProperty("generatedUtc").GetString());
            Assert.True(doc.TryGetProperty("migratedUtc", out _));
            Assert.DoesNotContain("Admin", doc.GetProperty("note").GetString(), StringComparison.Ordinal);

            // MariaDB's logins are unchanged, value for value, and the old test account is now the play account.
            var mariadb = doc.GetProperty("mariadb");
            Assert.Equal(["host", "port", "rootUser", "rootPassword", "aceUser", "acePassword"], mariadb.EnumerateObject().Select(p => p.Name));
            Assert.Equal(root, mariadb.GetProperty("rootPassword").GetString());
            Assert.Equal(ace, mariadb.GetProperty("acePassword").GetString());
            Assert.Equal(3316, mariadb.GetProperty("port").GetInt32());
            var accounts = doc.GetProperty("accounts");
            Assert.Equal("lifestone", accounts.GetProperty("play").GetProperty("username").GetString());
            Assert.Equal(play, accounts.GetProperty("play").GetProperty("password").GetString());
            Assert.Equal("lifestone-test", accounts.GetProperty("test").GetProperty("username").GetString());
            Assert.NotEqual(play, accounts.GetProperty("test").GetProperty("password").GetString());
            AssertNoPasswordIn(run, secrets);
        }

        AssertOwnerOnly(folder.Combine("secrets.json"));

        // Idempotent: a second run keeps the file byte for byte.
        var before = File.ReadAllBytes(folder.Combine("secrets.json"));
        var again = PowerShellHost.RunOk(shell, Config(folder) + "$r = Initialize-LsSecrets $cfg\nOut-Result $r.Action\n");
        Assert.Equal("kept", again.Result?.GetString());
        Assert.Equal(before, File.ReadAllBytes(folder.Combine("secrets.json")));
    }

    [Theory]
    [MemberData(nameof(Shells))]
    public void AddAccount_adds_an_entry_and_refuses_bad_names_reserved_keys_and_duplicates(string shell)
    {
        using var folder = new TempFolder();
        PowerShellHost.RunOk(shell, Config(folder) + "Initialize-LsSecrets $cfg | Out-Null\n");
        var add = PowerShellHost.RunOk(shell, Config(folder) + "Out-Result (Add-LsAccount -Cfg $cfg -Name 'alice-2')\n");
        Assert.Equal("alice-2", add.Result?.GetString());
        using (var secrets = ReadSecrets(folder))
        {
            var alice = secrets.RootElement.GetProperty("accounts").GetProperty("alice-2");
            Assert.Equal("alice-2", alice.GetProperty("username").GetString());
            Assert.Matches("^[A-Za-z0-9]{20}$", alice.GetProperty("password").GetString());
            Assert.Equal(["play", "test", "alice-2"], secrets.RootElement.GetProperty("accounts").EnumerateObject().Select(p => p.Name));
            AssertNoPasswordIn(add, secrets);
        }

        AssertOwnerOnly(folder.Combine("secrets.json"));
        var after = File.ReadAllBytes(folder.Combine("secrets.json"));
        string[] refused = ["play", "test", "Alice", "al", "-alice", "a_b", "lifestone", "lifestone-test", "alice-2", "lifestone-sentinel", new string('a', 51)];
        foreach (var name in refused)
        {
            var run = PowerShellHost.Run(shell, Config(folder) + "Add-LsAccount -Cfg $cfg -Name " + PowerShellHost.Quote(name) + " | Out-Null\n");
            Assert.True(run.ExitCode != 0, $"-AddAccount '{name}' must be refused:\n{run.AllText}");
        }

        Assert.Equal(after, File.ReadAllBytes(folder.Combine("secrets.json")));
        Assert.False(File.Exists(folder.Combine("secrets.json.tmp")));
    }

    [Theory]
    [MemberData(nameof(Shells))]
    public void A_write_that_would_lose_a_login_is_refused_and_changes_nothing(string shell)
    {
        using var folder = new TempFolder();
        PowerShellHost.RunOk(shell, Config(folder) + "Initialize-LsSecrets $cfg | Out-Null\n");
        var before = File.ReadAllBytes(folder.Combine("secrets.json"));

        // A rewrite that changes the play password, and one that drops accounts.test: both fail their checks.
        var changed = PowerShellHost.RunOk(shell, Config(folder) + """
            $old = Get-LsSecrets $cfg
            $doc = ConvertTo-LsSecretsDocument $old
            $doc.accounts.play.password = 'x' + $doc.accounts.play.password
            try { Write-LsSecrets -Cfg $cfg -Document $doc -Original $old; Out-Result 'written' } catch { Out-Result $_.Exception.Message }
            """);
        Assert.Contains("accounts.play.password changed", changed.Result?.GetString(), StringComparison.Ordinal);
        var dropped = PowerShellHost.RunOk(shell, Config(folder) + """
            $old = Get-LsSecrets $cfg
            $doc = ConvertTo-LsSecretsDocument $old
            $doc.accounts.Remove('test')
            try { Write-LsSecrets -Cfg $cfg -Document $doc -Original $old; Out-Result 'written' } catch { Out-Result $_.Exception.Message }
            """);
        Assert.Contains("accounts.test is missing", dropped.Result?.GetString(), StringComparison.Ordinal);

        Assert.Equal(before, File.ReadAllBytes(folder.Combine("secrets.json")));
        Assert.False(File.Exists(folder.Combine("secrets.json.tmp")));
        using var secrets = ReadSecrets(folder);
        AssertNoPasswordIn(changed, secrets);
        AssertNoPasswordIn(dropped, secrets);
    }

    [Theory]
    [MemberData(nameof(Shells))]
    public void The_leak_scan_counts_every_password_as_UTF8_and_UTF16_and_prints_none(string shell)
    {
        using var folder = new TempFolder();
        PowerShellHost.RunOk(shell, Config(folder) + "Initialize-LsSecrets $cfg | Out-Null\n");
        string play;
        string root;
        using (var secrets = ReadSecrets(folder))
        {
            play = secrets.RootElement.GetProperty("accounts").GetProperty("play").GetProperty("password").GetString()!;
            root = secrets.RootElement.GetProperty("mariadb").GetProperty("rootPassword").GetString()!;
        }

        var logs = Directory.CreateDirectory(folder.Combine("logs")).FullName;
        File.WriteAllText(Path.Combine(logs, "utf8.txt"), $"login {play} and again {play}; root {root}\n", new UTF8Encoding(false));
        File.WriteAllText(Path.Combine(logs, "utf16.txt"), $"login {play}\n", new UnicodeEncoding(false, false));
        File.WriteAllText(Path.Combine(logs, "clean.txt"), "nothing here\n", new UTF8Encoding(false));

        // The scan reads 4 MiB chunks that overlap by the longest needle less one byte (63 here): one copy before the
        // first chunk's end, one across it and one after it, each counted once.
        const int Chunk = 4 * 1024 * 1024;
        var big = new byte[Chunk + 200];
        Array.Fill(big, (byte)'.');
        foreach (var at in new[] { Chunk - 30, Chunk + 50, Chunk + 120 })
        {
            Encoding.UTF8.GetBytes(play).CopyTo(big, at);
        }

        File.WriteAllBytes(Path.Combine(logs, "big.log"), big);

        var run = PowerShellHost.RunOk(
            shell,
            Config(folder) + "Out-Result @(Find-LsSecretLeaks -Cfg $cfg -Path @(" + PowerShellHost.Quote(logs) + ", " + PowerShellHost.Quote(folder.Combine("secrets.json")) + ") | ForEach-Object { [pscustomobject]@{ File = [IO.Path]::GetFileName($_.File); Count = $_.Count } })\n");
        var counts = run.Result!.Value.EnumerateArray().ToDictionary(e => e.GetProperty("File").GetString()!, e => e.GetProperty("Count").GetInt32());
        Assert.Equal(new Dictionary<string, int> { ["big.log"] = 3, ["clean.txt"] = 0, ["utf16.txt"] = 1, ["utf8.txt"] = 3 }, counts);
        using var all = ReadSecrets(folder);
        AssertNoPasswordIn(run, all);
    }

    private static JsonDocument ReadSecrets(TempFolder folder) => JsonDocument.Parse(File.ReadAllBytes(folder.Combine("secrets.json")));

    private static string Random(int length) => RandomNumberGenerator.GetString("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789", length);

    /// <summary>No password of <paramref name="secrets"/> appears in anything the run printed.</summary>
    private static void AssertNoPasswordIn(PowerShellRun run, JsonDocument secrets)
    {
        var passwords = new List<string>();
        Collect(secrets.RootElement, passwords);
        Assert.NotEmpty(passwords);
        Assert.True(passwords.All(p => !run.AllText.Contains(p, StringComparison.Ordinal)), "a password appeared in the script's output");

        static void Collect(JsonElement element, List<string> into)
        {
            if (element.ValueKind != JsonValueKind.Object)
            {
                return;
            }

            foreach (var property in element.EnumerateObject())
            {
                if (property.Value.ValueKind == JsonValueKind.String && property.Name.Contains("password", StringComparison.OrdinalIgnoreCase))
                {
                    into.Add(property.Value.GetString()!);
                }

                Collect(property.Value, into);
            }
        }
    }

    /// <summary>The file's ACL has no inherited entries and grants access to the current user only (Protect-LsFile).</summary>
    private static void AssertOwnerOnly(string path)
    {
        if (!OperatingSystem.IsWindows())
        {
            return;
        }

        var security = new FileInfo(path).GetAccessControl();
        Assert.True(security.AreAccessRulesProtected, "secrets.json must not inherit its folder's permissions");
        var me = WindowsIdentity.GetCurrent().User!;
        var rules = security.GetAccessRules(includeExplicit: true, includeInherited: true, typeof(SecurityIdentifier)).Cast<FileSystemAccessRule>().ToArray();
        Assert.NotEmpty(rules);
        foreach (var rule in rules)
        {
            Assert.Equal(me, rule.IdentityReference);
        }
    }
}
