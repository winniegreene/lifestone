using System.Globalization;
using Lifestone.ServerTools;

namespace Lifestone.ServerMod;

/// <summary>What one step of the bot's emote answer to a talk or a give is.</summary>
internal enum BuffBotStepKind
{
    /// <summary>Turn to the teller.</summary>
    Turn,

    /// <summary>Tell the teller a line.</summary>
    Tell,

    /// <summary>Stamp the hook's key on the bot's own quest registry (ACE's <c>StampMyQuest</c>: a creature's registry is held in memory, Managers/QuestManager.cs 145-165 @95ef426d).</summary>
    Stamp,

    /// <summary>Activate the bot's activation target, the bot itself (ACE's <c>Activate</c> emote calls its <c>OnActivate</c> with the teller, EmoteManager.cs 81-94): the mod's code runs there.</summary>
    Activate,
}

/// <summary>One step of the bot's emote answer.</summary>
/// <param name="Kind">What it is.</param>
/// <param name="Text">The line told (a <see cref="BuffBotStepKind.Tell"/>) or the hook's key (a <see cref="BuffBotStepKind.Stamp"/>).</param>
internal readonly record struct BuffBotStep(BuffBotStepKind Kind, string? Text = null);

/// <summary>The bot's emote answer to one word or one give: the word it matches (null: any text no other answer matches), the ware a give answer takes (0: a talk), and its steps in order.</summary>
/// <param name="Word">The word, or null for the fallback (and for a give).</param>
/// <param name="Steps">The steps.</param>
/// <param name="GiveWcid">The ware of a give answer, or 0 for a talk.</param>
internal sealed record BuffBotAnswer(string? Word, IReadOnlyList<BuffBotStep> Steps, uint GiveWcid = 0);

/// <summary>One point of the walk to the shop: the cell ACE's position names and the landblock's metres.</summary>
/// <param name="Cell">The cell (outdoor or a building's room).</param>
/// <param name="X">The x in the landblock's metres.</param>
/// <param name="Y">The y.</param>
/// <param name="Z">The height.</param>
internal readonly record struct BuffBotWaypoint(uint Cell, float X, float Y, float Z);

/// <summary>
/// M6 item 14 (m6-plan.md section 3.1, D124-D127, D138): the rules of <see cref="BuffBot"/> with nothing from ACE in them, so Lifestone.ServerMod.Tests runs them (BuffBotRulesTests): whether the bot is placed, when
/// it is placed again, what it looks like and its numbers, its emote answers, the restock line and the walk to the shop. The day itself is <see cref="BuffBotDesk"/>'s, a cast <see cref="BuffBotCasting"/>'s, the trade
/// <see cref="BuffBotShop"/>'s and the pack <see cref="BuffBotLedger"/>'s.
/// </summary>
/// <remarks>
/// <para><b>No patch: the answers are hooks (D138).</b> The mod patches nothing in ACE, and ACE calls no mod code when a creature is told something or given something. A creature answers a direct talk with its own
/// emote sets (Managers/EmoteManager.cs 2047-2050, 1559-1660 @95ef426d), and a give with its Give emote set for the ware (Player_Inventory.cs 3417-3441, WorldObject.cs 265-285). So each answer is two steps: stamp
/// the hook's key on the bot's own quest registry, then <c>Activate</c>, whose target is the bot itself, so ACE calls the bot's <c>OnActivate</c> with the teller (the bot is the mod's own subclass of ACE's
/// creature, <c>BuffBotBody</c>); the code there reads the key, erases it and answers. The help line stays a plain emote tell.</para>
/// <para><b>The order of the answers matters.</b> ACE takes the first set that matches, in the list's order (every set has probability 1), and a set with no word matches every text: the fallback comes last.</para>
/// <para><b>A give takes one of a stack.</b> For an NPC with a Give emote ACE removes one item of the stack, whatever the amount asked (Player_Inventory.cs 3423-3425: only an NPC that accepts everything takes the
/// whole amount), and destroys it after the emote (3438-3440). So one give is one scarab and one credit, and the scarab joins the bot's pack in its ledger.</para>
/// <para><b>Its numbers (D138: a mage's, a round of 28 casts realistic but not crippling).</b> The body is Archmage Ichihiri's (Focus 290, Self 290). Creature Enchantment and Life Magic specialized at
/// <see cref="MagicInitLevel"/> + (Focus + Self) / 4 = 380; Mana Conversion trained at <see cref="ManaConversionInitLevel"/> + (Focus + Self) / 6 = 300; mana Self + <see cref="ManaInitLevel"/> = 900, regenerated by
/// ACE at <see cref="ManaRate"/> a heartbeat, x2.15 under its own Mana Renewal VII (<see cref="BuffBotSelf"/>). Every bot spell is level VII: power 300, base mana 70, ComponentLoss 0.15 (the dats). So a cast lands 99.63% of the
/// time (a fizzle every 270 casts), costs about 18 mana after Mana Conversion (a round of 28 about 500, which 900 covers once with room and ACE regenerates in about 20 minutes), and burns about 0.47 Prismatic
/// Tapers (four slots at 0.15 x 1.0 x 300/380) and 0.0036 Platinum Scarabs: about 13 tapers a round.</para>
/// </remarks>
internal static class BuffBotRules
{
    /// <summary>The environment variable that keeps the bot out of the world, read once when the world opens.</summary>
    public const string EnvironmentVariable = "LIFESTONE_BUFF_BOT";

    /// <summary>The value that keeps the bot out.</summary>
    public const string Off = "off";

    /// <summary>
    /// The creature the bot's body is taken from: Archmage Ichihiri (a Sho man, a plain creature with a human's motions; ACE-World-Database v0.9.296 weenie 43741). His attributes, body and look are
    /// read from ACE's weenie cache; his name, clothes and answers are not used, and his magic skills, mana and its rate are the bot's own (see the class).
    /// </summary>
    public const uint BodyWcid = 43741;

    /// <summary>
    /// What the bot wears (D126: a Sho in Koujia armour): the Koujia Breastplate 6003, Sleeves 6005 and Leggings 6004, with the body's own Kasa 5901 and Gloves 121. His feet are bare until slice S4
    /// settles the look.
    /// </summary>
    public static IReadOnlyList<uint> Worn { get; } = [6003, 6005, 6004, 5901, 121];

    /// <summary>The seconds between two looks at whether the bot stands in the world.</summary>
    public const double LookSeconds = 2.0;

    /// <summary>Creature Enchantment's and Life Magic's InitLevel (specialized): 380 with the body's (Focus + Self) / 4 = 145.</summary>
    public const uint MagicInitLevel = 235;

    /// <summary>Mana Conversion's InitLevel (trained): 300 with the body's (Focus + Self) / 6 = 96.</summary>
    public const uint ManaConversionInitLevel = 204;

    /// <summary>The mana vital's InitLevel: 900 with the body's Self 290.</summary>
    public const uint ManaInitLevel = 610;

    /// <summary>
    /// The mana ACE regenerates a heartbeat before enchantments (PropertyFloat ManaRate; the body's heartbeat is 5 s): the body's own 1 (weenie 43741, float 5). Its own Mana Renewal VII (Battlemage's Blessing,
    /// x2.15 in the world copy's spell table), which it now casts on itself (<see cref="BuffBotSelf"/>, the owner, 2026-11-17), multiplies it (Creature_Vitals.cs 120-134 @95ef426d); until then the weenie said 2.15
    /// for the spell it did not cast.
    /// </summary>
    public const double ManaRate = 1.0;

    /// <summary>The Prismatic Taper's weenie (the foci formula's taper, component 188).</summary>
    public const uint TaperWcid = 20631;

    /// <summary>The taper's plural name, for the out-of line.</summary>
    public const string TaperName = "Prismatic Tapers";

    /// <summary>The Platinum Scarab's plural name.</summary>
    public const string ScarabName = "Platinum Scarabs";

    /// <summary>The owner's restock line (2026-11-14): under this many tapers, with no round in hand, the bot goes to the shop.</summary>
    public const int RestockUnder = 100;

    /// <summary>The tapers a trip buys up to: one stack (the climber's own keep).</summary>
    public const int RestockTo = 1000;

    /// <summary>The Platinum Scarabs the bot keeps for its own casting (about 0.1 a round: a hundred rounds); it sells those over this at the shop.</summary>
    public const int ScarabKeep = 10;

    /// <summary>The seconds after a round before it leaves (the owner, 2026-11-14: they give the customer time to finish).</summary>
    public const double LeaveDelaySeconds = 10;

    /// <summary>The seconds after a failed trip before another is tried.</summary>
    public const double RetryTripSeconds = 600;

    /// <summary>Archmage Cindrue's object id in Holtburg (weenie 2304, cell 0xA9B4011B: the profiles' vendor row; she sells the Prismatic Taper and buys spell components).</summary>
    public const uint CindrueGuid = 0x7A9B4033;

    /// <summary>Her weenie.</summary>
    public const uint CindrueWcid = 2304;

    /// <summary>The metres within which a walk's point counts as reached.</summary>
    public const float ArriveMetres = 1.0f;

    /// <summary>
    /// The walk from the bot's post to Archmage Cindrue's entry hall (her stop point, under her floor, as the climber's shop step stands): the journeys' leg planner's route on the retail dats, read 2026-11-14
    /// and pinned by <c>BuffBotRouteDatTests</c>: down the hill (outdoor cells 0x23, 0x35, 0x36) to her front door 0x7A9B4009, through its doorway room 0x0118 into the hall 0x0117. About 156 m. ACE's creature
    /// move-to walks each leg in a straight line; the front door opens to a creature with <c>AiOptions</c> 1 that walks into it (Door.cs 252-262). The way back is the same points in reverse.
    /// </summary>
    public static IReadOnlyList<BuffBotWaypoint> ShopRoute { get; } =
    [
        new(BuffBotWire.Cell, BuffBotWire.X, BuffBotWire.Y, 94.0f),
        new(0xA9B40023, 106.5f, 58.5f, 87.87f),
        new(0xA9B40035, 145.5f, 97.5f, 66.0f),
        new(0xA9B40036, 146.78f, 129.86f, 66.0f),
        new(0xA9B40036, 148.19f, 131.28f, 66.0f),
        new(0xA9B40118, 148.65f, 131.74f, 66.0f),
        new(0xA9B40117, 149.25f, 132.34f, 66.0f),
        new(0xA9B40117, 152.3f, 132.5f, 66.0f),
    ];

    /// <summary>The key a hook stamps: the prefix of every key.</summary>
    public const string HookPrefix = "LifestoneBuffBot_";

    /// <summary>The key of a word's hook.</summary>
    /// <param name="profile">The word's profile.</param>
    public static string WordKey(BuffBotProfile profile) => HookPrefix + "word_" + (profile ?? throw new ArgumentNullException(nameof(profile))).Key;

    /// <summary>The key of the credit word's hook.</summary>
    public const string CreditsKey = HookPrefix + "credits";

    /// <summary>The key of a give's hook.</summary>
    public const string GiveKey = HookPrefix + "give";

    /// <summary>True unless the variable says <see cref="Off"/> (ignoring case and the spaces at its ends).</summary>
    /// <param name="value">The variable's value, or null when it is not set.</param>
    public static bool IsOn(string? value) => !string.Equals(value?.Trim(), Off, StringComparison.OrdinalIgnoreCase);

    /// <summary>
    /// True when the bot is to be placed now: it does not stand in the world (never placed, or destroyed with its landblock: ACE destroys an unsaved object when the block unloads, Entity/Landblock.cs
    /// 1141-1145) and a player stands on its landblock, so the block is loaded and stays so.
    /// </summary>
    /// <param name="stands">The bot stands in the world.</param>
    /// <param name="playerOnBlock">A player is on <see cref="BuffBotWire.Landblock"/>.</param>
    public static bool PlaceNow(bool stands, bool playerOnBlock) => !stands && playerOnBlock;

    /// <summary>The bot's emote answers, in ACE's matching order: each profile's words, the credit word, the help word, the fallback for any other text, and the give of the fee's ware.</summary>
    public static IReadOnlyList<BuffBotAnswer> Answers()
    {
        var answers = new List<BuffBotAnswer>();
        foreach (var profile in BuffBotWire.Profiles)
        {
            IReadOnlyList<BuffBotStep> steps = [new(BuffBotStepKind.Stamp, WordKey(profile)), new(BuffBotStepKind.Activate)];
            answers.AddRange(profile.Words.Select(word => new BuffBotAnswer(word, steps)));
        }

        answers.Add(new BuffBotAnswer(BuffBotWire.CreditWord, [new(BuffBotStepKind.Stamp, CreditsKey), new(BuffBotStepKind.Activate)]));
        IReadOnlyList<BuffBotStep> help = [new(BuffBotStepKind.Turn), new(BuffBotStepKind.Tell, BuffBotWire.Help)];
        answers.Add(new BuffBotAnswer(BuffBotWire.HelpWord, help));
        answers.Add(new BuffBotAnswer(null, help));
        answers.Add(new BuffBotAnswer(null, [new(BuffBotStepKind.Stamp, GiveKey), new(BuffBotStepKind.Activate)], BuffBotWire.FeeWcid));
        return answers;
    }

    /// <summary>The hook the bot's quest registry holds (the keys its answers stamp), or null when it holds none or more than one of the bot's keys (named by <paramref name="why"/>).</summary>
    /// <param name="questNames">The names in the bot's registry.</param>
    /// <param name="why">Why no hook was read.</param>
    public static BuffBotHook? ReadHook(IEnumerable<string> questNames, out string? why)
    {
        ArgumentNullException.ThrowIfNull(questNames);
        var keys = questNames.Where(n => n.StartsWith(HookPrefix, StringComparison.OrdinalIgnoreCase)).ToList();
        why = null;
        if (keys.Count != 1)
        {
            why = string.Create(CultureInfo.InvariantCulture, $"{keys.Count} hook keys in the bot's registry ({string.Join(", ", keys)}), not one");
            return null;
        }

        var key = keys[0];
        if (string.Equals(key, CreditsKey, StringComparison.OrdinalIgnoreCase))
        {
            return new BuffBotHook(BuffBotHookKind.Credits);
        }

        if (string.Equals(key, GiveKey, StringComparison.OrdinalIgnoreCase))
        {
            return new BuffBotHook(BuffBotHookKind.Give);
        }

        foreach (var profile in BuffBotWire.Profiles)
        {
            if (string.Equals(key, WordKey(profile), StringComparison.OrdinalIgnoreCase))
            {
                return new BuffBotHook(BuffBotHookKind.Word, profile);
            }
        }

        why = "the key '" + key + "' names no hook";
        return null;
    }
}
