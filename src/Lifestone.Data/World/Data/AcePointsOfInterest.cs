using System.Globalization;
using System.Numerics;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace Lifestone.Data.World.Data;

/// <summary>
/// One teleport destination from ACE's world database: a point of interest and the Destination position of the portal
/// weenie it names (what ACE's <c>@telepoi</c> command teleports to).
/// </summary>
/// <param name="DisplayName">The place, from the portal weenie's name ("Portal to Holtburg" -&gt; "Holtburg").</param>
/// <param name="PoiNames">ACE's <c>points_of_interest</c> names for it (aliases, e.g. "Hotel", "Swank").</param>
/// <param name="Wcid">The portal weenie class id.</param>
/// <param name="WeenieClassName">ACE <c>weenie.class_Name</c>.</param>
/// <param name="WeenieName">The weenie's <c>PropertyString.Name</c>.</param>
/// <param name="CellId">Destination cell (outdoor 0x0001-0x0040 or EnvCell 0x0100+).</param>
/// <param name="Origin">Destination origin in the cell's landblock frame (AC metres).</param>
/// <param name="Rotation">Destination rotation (dat order W, X, Y, Z in ACE; stored here as a System.Numerics quaternion).</param>
public sealed record AcePointOfInterest(
    string DisplayName,
    IReadOnlyList<string> PoiNames,
    uint Wcid,
    string? WeenieClassName,
    string? WeenieName,
    uint CellId,
    Vector3 Origin,
    Quaternion Rotation);

/// <summary>
/// The AGPL-3.0 extract <c>World/Data/ace-world-points-of-interest.json</c> (embedded in this assembly; generated by
/// <c>tools/data/extract_ace_poi.py</c> from ACE-World-Database-v0.9.296.sql, see docs/third-party/sky-nav.md).
/// </summary>
public static class AcePointsOfInterest
{
    public const string FileName = "ace-world-points-of-interest.json";

    /// <summary>Manifest name of the embedded copy (Lifestone.Data.csproj).</summary>
    public const string ResourceName = "Lifestone.Data.World.Data." + FileName;

    private static readonly Lazy<IReadOnlyList<AcePointOfInterest>> Embedded = new(LoadEmbeddedCore);

    /// <summary>The embedded extract (parsed once). Throws when the resource is missing.</summary>
    public static IReadOnlyList<AcePointOfInterest> All => Embedded.Value;

    /// <summary>Parses the JSON text of the extract.</summary>
    public static IReadOnlyList<AcePointOfInterest> Parse(string json)
    {
        var doc = JsonSerializer.Deserialize<FileDto>(json, JsonOptions)
                  ?? throw new InvalidDataException($"{FileName}: empty document.");
        if (doc.Destinations is null || doc.Destinations.Count == 0)
        {
            throw new InvalidDataException($"{FileName}: no destinations.");
        }

        var result = new List<AcePointOfInterest>(doc.Destinations.Count);
        foreach (var d in doc.Destinations)
        {
            if (string.IsNullOrWhiteSpace(d.DisplayName) || d.Cell is null || d.Origin is not { Length: 3 } o || d.RotationWxyz is not { Length: 4 } q)
            {
                throw new InvalidDataException($"{FileName}: destination {d.Wcid} is incomplete.");
            }

            var cellText = d.Cell.StartsWith("0x", StringComparison.OrdinalIgnoreCase) ? d.Cell[2..] : d.Cell;
            if (!uint.TryParse(cellText, NumberStyles.AllowHexSpecifier, CultureInfo.InvariantCulture, out var cell))
            {
                throw new InvalidDataException($"{FileName}: destination {d.Wcid} has a bad cell '{d.Cell}'.");
            }

            result.Add(new AcePointOfInterest(
                d.DisplayName,
                d.PoiNames ?? [],
                d.Wcid,
                d.WeenieClassName,
                d.WeenieName,
                cell,
                new Vector3(o[0], o[1], o[2]),
                new Quaternion(q[1], q[2], q[3], q[0])));
        }

        return result;
    }

    private static IReadOnlyList<AcePointOfInterest> LoadEmbeddedCore()
    {
        using var stream = typeof(AcePointsOfInterest).Assembly.GetManifestResourceStream(ResourceName)
                           ?? throw new FileNotFoundException($"{ResourceName} is not embedded in Lifestone.Data.");
        using var reader = new StreamReader(stream);
        return Parse(reader.ReadToEnd());
    }

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNameCaseInsensitive = true,
        ReadCommentHandling = JsonCommentHandling.Skip,
    };

    private sealed class FileDto
    {
        [JsonPropertyName("destinations")]
        public List<DestinationDto>? Destinations { get; set; }
    }

    private sealed class DestinationDto
    {
        public string? DisplayName { get; set; }

        public List<string>? PoiNames { get; set; }

        public uint Wcid { get; set; }

        public string? WeenieClassName { get; set; }

        public string? WeenieName { get; set; }

        public string? Cell { get; set; }

        public float[]? Origin { get; set; }

        public float[]? RotationWxyz { get; set; }
    }
}
